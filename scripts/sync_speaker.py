"""Hands the speaker button of src/tts_suite/service/ui/speaker/ to every program that shows it (the list: scripts/speaker-consumers.json).

    python3 scripts/sync_speaker.py          writes the copies
    python3 scripts/sync_speaker.py --check  changes nothing; exit 1 where a copy differs from the source

Per kind of program:
  vue   speaker.css is copied; the component (props `from` and `playing`) is made from speaker.svg and speaker-from.svg.
Nothing here is edited by hand in the programs: a change belongs in speaker/, then this runs again.
"""
import argparse
import json
import os
import sys
from dataclasses import dataclass
from pathlib import Path

SUITE = Path(__file__).resolve().parent.parent
SOURCE = SUITE / "src" / "tts_suite" / "service" / "ui" / "speaker"
CONSUMERS = Path(__file__).resolve().parent / "speaker-consumers.json"
# The repos sit next to each other (the list gives their folder names).
REPOS = SUITE.parent

GENERATED = "Generated by TTS-Suite/scripts/sync_speaker.py from src/tts_suite/service/ui/speaker/: do not edit, change the source in the TTS-Suite."
SVG_NAMESPACE = ' xmlns="http://www.w3.org/2000/svg"'
FROM_ROOT_CLASS = ' class="speaker-from"'


@dataclass(frozen=True)
class Copy:
    """What a program should hold: its file and the content the source gives it."""
    path: Path
    content: str


def _indented(svg: str, spaces: int) -> str:
    return "".join(f"{' ' * spaces}{line}\n" if line else "\n" for line in svg.strip().splitlines())


def vue_component(icon_svg: str, from_svg: str, css_import: str) -> str:
    if SVG_NAMESPACE not in icon_svg or SVG_NAMESPACE not in from_svg or FROM_ROOT_CLASS not in from_svg:
        raise ValueError(f"speaker svg files: the roots need the namespace, and speaker-from.svg {FROM_ROOT_CLASS.strip()}")
    icon = icon_svg.replace(SVG_NAMESPACE, "")
    arrow = from_svg.replace(SVG_NAMESPACE, "").replace(FROM_ROOT_CLASS, f' v-if="from"{FROM_ROOT_CLASS}')
    return (
        f"<!-- {GENERATED} -->\n"
        '<script setup lang="ts">\n'
        f'import "{css_import}";\n'
        "defineProps<{ from?: boolean; playing?: boolean }>();\n"
        "</script>\n\n"
        "<template>\n"
        '  <span class="speaker" :class="{ playing }">\n'
        f"{_indented(icon, 4)}{_indented(arrow, 4)}"
        "  </span>\n"
        "</template>\n"
    )


def css_import_path(css: Path, component: Path) -> str:
    relative = os.path.relpath(css, component.parent)
    return relative if relative.startswith(".") else f"./{relative}"


def copies_for(consumer: dict[str, str]) -> list[Copy]:
    kind = consumer["kind"]
    if kind == "source":
        return []
    if kind != "vue":
        raise ValueError(f"{consumer['name']}: unknown kind {kind!r}")
    repo = REPOS / consumer["repo"]
    css_file = repo / consumer["css"]
    component = repo / consumer["component"]
    icon_svg = (SOURCE / "speaker.svg").read_text(encoding="utf-8")
    from_svg = (SOURCE / "speaker-from.svg").read_text(encoding="utf-8")
    return [
        Copy(css_file, (SOURCE / "speaker.css").read_text(encoding="utf-8")),
        Copy(component, vue_component(icon_svg, from_svg, css_import_path(css_file, component))),
    ]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="change nothing; exit 1 where a copy differs")
    check_only = parser.parse_args().check
    consumers = json.loads(CONSUMERS.read_text(encoding="utf-8"))["buttons"]
    outdated = 0
    for consumer in consumers:
        for copy in copies_for(consumer):
            current = copy.path.read_text(encoding="utf-8") if copy.path.exists() else None
            if current == copy.content:
                continue
            outdated += 1
            print(f"{consumer['name']}: {copy.path.relative_to(REPOS)} {'differs' if check_only else 'written'}")
            if not check_only:
                copy.path.parent.mkdir(parents=True, exist_ok=True)
                copy.path.write_text(copy.content, encoding="utf-8")
    if outdated == 0:
        print("All copies are up to date.")
    return 1 if check_only and outdated else 0


if __name__ == "__main__":
    sys.exit(main())

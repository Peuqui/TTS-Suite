"""The sync script that hands the speaker button of ui/speaker/ to the programs (scripts/sync_speaker.py)."""
import json
import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "scripts"))
import sync_speaker

ICON_SVG = (sync_speaker.SOURCE / "speaker.svg").read_text(encoding="utf-8")
FROM_SVG = (sync_speaker.SOURCE / "speaker-from.svg").read_text(encoding="utf-8")
KEYS_PER_KIND = {
    "source": {"name", "kind", "repo", "uses"},
    "vue": {"name", "kind", "repo", "uses", "css", "component"},
}


def test_vue_component_has_the_props_and_the_arrow_only_on_from() -> None:
    component = sync_speaker.vue_component(ICON_SVG, FROM_SVG, "../assets/speaker/speaker.css")
    assert component.startswith("<!-- Generated by TTS-Suite/scripts/sync_speaker.py")
    assert 'import "../assets/speaker/speaker.css";' in component
    assert "defineProps<{ from?: boolean; playing?: boolean }>();" in component
    assert '<span class="speaker" :class="{ playing }">' in component
    assert 'v-if="from" class="speaker-from"' in component
    assert "xmlns" not in component
    assert component.count("<line ") == 5


def test_vue_component_refuses_a_source_without_the_arrow_class() -> None:
    with pytest.raises(ValueError, match="speaker svg files"):
        sync_speaker.vue_component(ICON_SVG, '<svg xmlns="http://www.w3.org/2000/svg"></svg>', "./speaker.css")


def test_css_import_path_is_relative_to_the_component() -> None:
    css = Path("/r/frontend/src/assets/speaker/speaker.css")
    assert sync_speaker.css_import_path(css, Path("/r/frontend/src/components/SpeakerIcon.vue")) == "../assets/speaker/speaker.css"
    assert sync_speaker.css_import_path(css, Path("/r/frontend/src/assets/Icon.vue")) == "./speaker/speaker.css"


def test_every_consumer_of_the_list_has_what_its_kind_needs() -> None:
    consumers = json.loads(sync_speaker.CONSUMERS.read_text(encoding="utf-8"))["buttons"]
    assert {consumer["name"] for consumer in consumers} >= {"TTS-Suite", "AIfred-Intelligence", "Agent-Orc"}
    for consumer in consumers:
        assert set(consumer) == KEYS_PER_KIND[consumer["kind"]], consumer["name"]
